function t(key,vars){
  let s=(T[curLang]&&T[curLang][key])!=null?T[curLang][key]:(T.it[key]!=null?T.it[key]:key);
  if(vars)for(const k in vars)s=s.split('{'+k+'}').join(vars[k]);
  return s;
}
function plural(n,one,many){return n===1?one:many}
const accSym=a=>a>0?'♯':a<0?'♭':'';
function keyNameFor(sf){
  const row=KEY_TABLE[sf]||KEY_TABLE[0],L=LETTERS[curLang]||LETTERS.it,[mw,mn]=MAJMIN[curLang]||MAJMIN.it;
  const maj=L[row[0]]+accSym(row[1]),min=L[row[2]]+accSym(row[3]);
  return `${maj} ${mw} / ${min} ${mn}`+(sf?` (${Math.abs(sf)}${sf>0?'♯':'♭'})`:'');
}
function clefNameFor(id){const row=CLEF_NAMES[id];return row?(row[curLang]||row.it):id}
function instNameFor(id){const row=INST_NAMES[id];return row?(row[curLang]||row.it):id}
function durNameFor(id){const row=DUR_NAMES[id];return row?(row[curLang]||row.it):id}
function durLabel(id,dot){
  const name=durNameFor(id);
  if(curLang==='en')return dot?'Dotted '+name.charAt(0).toLowerCase()+name.slice(1):name;
  return dot?name+' '+t('dur.dotted'):name;
}
/* Applica le traduzioni al markup statico: data-i18n (testo), data-i18n-html (HTML, es. i tasti nel suggerimento),
   data-i18n-title, data-i18n-ph (placeholder), data-i18n-aria (aria-label). */
function applyStaticI18n(root){
  const scope=root||document;
  scope.querySelectorAll('[data-i18n]').forEach(el=>{el.textContent=t(el.getAttribute('data-i18n'))});
  scope.querySelectorAll('[data-i18n-html]').forEach(el=>{el.innerHTML=t(el.getAttribute('data-i18n-html'))});
  scope.querySelectorAll('[data-i18n-title]').forEach(el=>{el.title=t(el.getAttribute('data-i18n-title'))});
  scope.querySelectorAll('[data-i18n-ph]').forEach(el=>{el.placeholder=t(el.getAttribute('data-i18n-ph'))});
  scope.querySelectorAll('[data-i18n-aria]').forEach(el=>{el.setAttribute('aria-label',t(el.getAttribute('data-i18n-aria')))});
}
